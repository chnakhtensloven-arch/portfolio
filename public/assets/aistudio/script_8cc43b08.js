let currentLanguage = 'en';
let typingTimer = 0;

const getStoredLanguage = () => {
    try {
        return localStorage.getItem('portfolio-language');
    } catch (error) {
        return null;
    }
};

const saveLanguage = (language) => {
    try {
        localStorage.setItem('portfolio-language', language);
    } catch (error) {
        // The page can still switch languages if browser storage is unavailable.
    }
};

const applyLanguage = (language) => {
    currentLanguage = language === 'ar' ? 'ar' : 'en';
    const dictionary = translations[currentLanguage];
    document.documentElement.lang = currentLanguage;
    document.documentElement.dir = currentLanguage === 'ar' ? 'rtl' : 'ltr';

    document.querySelectorAll('[data-i18n]').forEach((element) => {
        const key = element.dataset.i18n;
        if (dictionary[key] !== undefined) element.textContent = dictionary[key];
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
        const key = element.dataset.i18nPlaceholder;
        if (dictionary[key] !== undefined) element.setAttribute('placeholder', dictionary[key]);
    });
    document.querySelectorAll('[data-i18n-aria-label]').forEach((element) => {
        const key = element.dataset.i18nAriaLabel;
        if (dictionary[key] !== undefined) element.setAttribute('aria-label', dictionary[key]);
    });

    const toggle = document.getElementById('language-toggle');
    if (toggle) {
        const isArabic = currentLanguage === 'ar';
        toggle.setAttribute('aria-pressed', String(isArabic));
        toggle.setAttribute(
            'aria-label',
            translations[currentLanguage][isArabic ? 'Switch language to English' : 'Switch language to Arabic']
        );
        toggle.querySelectorAll('[data-language-option]').forEach((option) => {
            option.classList.toggle('is-active', option.dataset.languageOption === currentLanguage);
        });
    }

    const formButtonText = document.getElementById('btn-text');
    if (formButtonText?.dataset.isSending === 'true') {
        formButtonText.textContent = dictionary['Sending...'];
    }

    document.querySelectorAll('img[data-i18n-alt]').forEach((image) => {
        const key = image.dataset.i18nAlt;
        if (dictionary[key] !== undefined) image.setAttribute('alt', dictionary[key]);
    });
};

const startTypingEffect = () => {
    const heroRole = document.getElementById('hero-role');
    const prefersReducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
    if (!heroRole) return;

    window.clearTimeout(typingTimer);
    const configuredRole = window.portfolioConfig?.hero?.role || 'Web Developer';
    const roles = [...new Set([configuredRole, 'Front-End Developer', 'E-commerce Developer'])];
    const localizedRoles = roles.map((role) => translations[currentLanguage][role] || role);
    const baseRole = translations[currentLanguage][configuredRole] || configuredRole;
    let roleIndex = 0;
    let isDeleting = false;
    let currentText = baseRole;
    heroRole.textContent = baseRole;
    heroRole.classList.toggle('kinetic-typing-caret', !prefersReducedMotion);
    if (prefersReducedMotion) return;

    const typeNextCharacter = () => {
        const targetRole = localizedRoles[roleIndex];
        currentText = isDeleting
            ? targetRole.slice(0, Math.max(0, currentText.length - 1))
            : targetRole.slice(0, currentText.length + 1);
        heroRole.textContent = currentText;

        let delay = isDeleting ? 42 : 78;
        if (!isDeleting && currentText === targetRole) {
            isDeleting = true;
            delay = 1450;
        } else if (isDeleting && currentText.length === 0) {
            isDeleting = false;
            roleIndex = (roleIndex + 1) % localizedRoles.length;
            delay = 280;
        }
        typingTimer = window.setTimeout(typeNextCharacter, delay);
    };

    typingTimer = window.setTimeout(() => {
        isDeleting = true;
        typingTimer = window.setTimeout(typeNextCharacter, 1200);
    }, 1800);
};

const initializePortfolio = () => {
    updateEditablePortfolio();
    const savedLanguage = getStoredLanguage();
    applyLanguage(savedLanguage === 'ar' ? 'ar' : 'en');
    startTypingEffect();

    document.getElementById('language-toggle')?.addEventListener('click', () => {
        const nextLanguage = currentLanguage === 'en' ? 'ar' : 'en';
        applyLanguage(nextLanguage);
        saveLanguage(nextLanguage);
        startTypingEffect();
    });

    document.querySelectorAll('img[data-fallback-src]').forEach((image) => {
        image.addEventListener('error', () => {
            if (image.dataset.fallbackApplied) return;
            image.dataset.fallbackApplied = 'true';
            image.src = image.dataset.fallbackSrc;
        });
    });

    const menuButton = document.getElementById('menu-btn');
    const mobileMenu = document.getElementById('mobile-menu');
    const menuIcon = menuButton?.querySelector('i');
    const setMenuState = (isOpen) => {
        if (!menuButton || !mobileMenu) return;
        menuButton.setAttribute('aria-expanded', String(isOpen));
        mobileMenu.classList.toggle('hidden', !isOpen);
        menuIcon?.classList.toggle('fa-bars', !isOpen);
        menuIcon?.classList.toggle('fa-xmark', isOpen);
    };

    menuButton?.addEventListener('click', () => {
        setMenuState(mobileMenu?.classList.contains('hidden') ?? true);
    });
    mobileMenu?.querySelectorAll('a').forEach((link) => {
        link.addEventListener('click', () => setMenuState(false));
    });
    document.addEventListener('keydown', (event) => {
        if (event.key === 'Escape') setMenuState(false);
    });

    const desktopMenuQuery = window.matchMedia('(min-width: 768px)');
    const closeMenuOnDesktop = (event) => {
        if (event.matches) setMenuState(false);
    };
    if (desktopMenuQuery.addEventListener) {
        desktopMenuQuery.addEventListener('change', closeMenuOnDesktop);
    } else {
        desktopMenuQuery.addListener(closeMenuOnDesktop);
    }
    setMenuState(false);

    const navbar = document.getElementById('navbar');
    const sections = [...document.querySelectorAll('main section[id]')];
    const navigationLinks = [...document.querySelectorAll('.nav-link')];
    const scrollProgress = document.createElement('div');
    scrollProgress.className = 'scroll-progress';
    scrollProgress.setAttribute('aria-hidden', 'true');
    document.body.append(scrollProgress);

    let scrollFrame = 0;
    const updateScrollState = () => {
        scrollFrame = 0;
        const scrollPosition = window.scrollY + (navbar?.offsetHeight ?? 80) + 40;
        const scrollableDistance = document.documentElement.scrollHeight - window.innerHeight;
        const progress = scrollableDistance > 0
            ? Math.min(window.scrollY / scrollableDistance, 1) * 100
            : 0;
        scrollProgress.style.width = `${progress}%`;

        let activeSection = '';
        sections.forEach((section) => {
            if (scrollPosition >= section.offsetTop) activeSection = section.id;
        });
        navigationLinks.forEach((link) => {
            const isActive = link.getAttribute('href') === `#${activeSection}`;
            link.classList.toggle('text-primary', isActive);
            link.classList.toggle('bg-surface-card', isActive);
            link.classList.toggle('text-white', isActive);
            link.classList.toggle('text-gray-400', !isActive);
            if (isActive) link.setAttribute('aria-current', 'location');
            else link.removeAttribute('aria-current');
        });
        navbar?.classList.toggle('is-scrolled', window.scrollY > 16);
    };
    const requestScrollUpdate = () => {
        if (!scrollFrame) scrollFrame = window.requestAnimationFrame(updateScrollState);
    };
    window.addEventListener('scroll', requestScrollUpdate, { passive: true });
    window.addEventListener('resize', requestScrollUpdate, { passive: true });
    updateScrollState();

    const prefersReducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
    const heroColumns = [...document.querySelectorAll('#home > div')];
    heroColumns.forEach((column, index) => {
        column.classList.add('kinetic-hero-enter');
        column.style.setProperty('--hero-delay', `${index * 140}ms`);
    });

    const revealTargets = [
        ...document.querySelectorAll('#about > .text-center, #about > .grid'),
        ...document.querySelectorAll('#services > .text-center, #services > .grid > div'),
        ...document.querySelectorAll('#skills > .text-center, #skills > .grid > div'),
        ...document.querySelectorAll('#projects > .text-center, #projects > .grid > div'),
        ...document.querySelectorAll('#contact > .text-center, #contact > .bg-surface-card')
    ];
    revealTargets.forEach((element) => {
        element.classList.add('kinetic-reveal');
        const revealSiblings = [...element.parentElement.children].filter((sibling) =>
            sibling.classList.contains('kinetic-reveal')
        );
        element.style.setProperty('--reveal-delay', `${revealSiblings.indexOf(element) * 100}ms`);
    });

    const skillBars = [...document.querySelectorAll('#skills .skill-progress')];
    skillBars.forEach((bar) => {
        bar.dataset.targetWidth = bar.dataset.width || '0%';
        bar.style.width = '0%';
    });

    const revealElement = (element) => {
        element.classList.add('is-visible');
        element.querySelectorAll('.skill-progress').forEach((bar) => {
            bar.style.width = bar.dataset.targetWidth || '0%';
        });
    };

    if (prefersReducedMotion || !('IntersectionObserver' in window)) {
        revealTargets.forEach(revealElement);
        skillBars.forEach((bar) => {
            bar.style.width = bar.dataset.targetWidth || '0%';
        });
    } else {
        const revealObserver = new IntersectionObserver((entries, observer) => {
            entries.forEach((entry) => {
                if (!entry.isIntersecting) return;
                revealElement(entry.target);
                observer.unobserve(entry.target);
            });
        }, { threshold: 0.14, rootMargin: '0px 0px -40px 0px' });

        revealTargets.forEach((element) => revealObserver.observe(element));
    }

    document.querySelectorAll('#home .relative.w-80 > .absolute').forEach((badge, index) => {
        if (index === 1) badge.classList.add('kinetic-float');
        if (index === 2) badge.classList.add('kinetic-float-delayed');
    });

    const hoverCards = document.querySelectorAll(
        '#services .grid > div, #projects .grid > div, #about .grid.grid-cols-2 > div'
    );
    const canHover = window.matchMedia('(hover: hover) and (pointer: fine)').matches;
    hoverCards.forEach((card) => {
        card.classList.add('kinetic-card');
        if (!canHover || prefersReducedMotion) return;

        card.addEventListener('pointermove', (event) => {
            const bounds = card.getBoundingClientRect();
            const relativeX = (event.clientX - bounds.left) / bounds.width;
            const relativeY = (event.clientY - bounds.top) / bounds.height;
            const rotateY = (relativeX - 0.5) * 8;
            const rotateX = (0.5 - relativeY) * 8;
            card.style.transform = `perspective(900px) rotateX(${rotateX}deg) rotateY(${rotateY}deg) translateY(-4px)`;
        });
        card.addEventListener('pointerleave', () => {
            card.style.transform = '';
        });
    });

    const contactForm = document.getElementById('contact-form');
    const formStatus = document.getElementById('form-status');
    const buttonText = document.getElementById('btn-text');
    contactForm?.addEventListener('submit', (event) => {
        event.preventDefault();
        if (buttonText) {
            buttonText.dataset.isSending = 'true';
            buttonText.textContent = translations[currentLanguage]['Sending...'];
        }

        window.setTimeout(() => {
            contactForm.reset();
            if (buttonText) {
                delete buttonText.dataset.isSending;
                buttonText.textContent = translations[currentLanguage]['Send Message'];
            }
            if (!formStatus) return;

            formStatus.classList.remove('hidden');
            window.setTimeout(() => formStatus.classList.add('hidden'), 4500);
        }, 800);
    });
};

